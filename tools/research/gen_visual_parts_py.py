"""Generate worlds/nfsu/data/visual_parts.py from the NFS Wiki visual part pages (visual_raw.json written by
fetch_visual.py). Usage: gen_visual_parts_py.py <research dir> <output .py>"""
import json
import re
import sys
import pathlib

research = pathlib.Path(sys.argv[1])
out_path = pathlib.Path(sys.argv[2])
raw = json.loads((research / "visual_raw.json").read_text(encoding="utf-8"))

# Categories that become single-part items (rims, paint and decals stay progressive).
CATEGORIES = {
    "Body/Front Bumper": "Front Bumper", "Body/Rear Bumper": "Rear Bumper", "Body/Side Skirts": "Side Skirts",
    "Body/Spoiler": "Spoiler", "Body/Hood": "Hood", "Body/Roof Scoop": "Roof Scoop",
    "Accessories/Neon": "Neon", "Accessories/Headlights": "Headlights", "Accessories/Taillights": "Taillights",
    "Accessories/Muffler Tip": "Muffler Tip", "Accessories/Window Tinting": "Window Tint",
}

parts = []
for key, category in CATEGORIES.items():
    text = raw[key]
    level = None
    for line in text.splitlines():
        h = re.match(r"^={2,4}\s*(.*?)\s*={2,4}\s*$", line)
        if h:
            m = re.match(r"level (\d)", h.group(1).lower())
            level = int(m.group(1)) if m else ("u" if "unique" in h.group(1).lower() else level)
            continue
        m = re.match(r"^[^|]+\|'''(.+?)'''<br>\{\{NFSUG1_PartUnlock\|([^|}]*)\|([^|}]*)", line)
        if not m:
            continue
        name, cost, rep = m.group(1).strip(), m.group(2).strip(), m.group(3).strip()
        if cost.lower() == "u" or level == "u":
            continue  # unique time-trial rewards are separate items
        lvl = level if isinstance(level, int) else 3  # head/taillights have no level heading (Level 3)
        parts.append((category, name, lvl, int(cost), float(rep)))

# de-duplicate (some pages list the same design twice for body types)
seen, unique = set(), []
for p in parts:
    if (p[0], p[1]) not in seen:
        seen.add((p[0], p[1]))
        unique.append(p)

lines = [f"    VisualPart({c!r}, {n!r}, {lv}, {cost}, {rep}),"
         for c, n, lv, cost, rep in unique]
header = '''"""Single visual parts of Need for Speed: Underground (PS2), one item each in Archipelago.

Generated by tools/research/gen_visual_parts_py.py from the NFS Wiki visual customisation pages
(https://nfs.fandom.com/wiki/Need_for_Speed:_Underground/Customisation/Visual, retrieved 2026-11-04).
"rep" = reputation (stars) the wiki lists for the part. Rims, paint and decals stay progressive items.
"""
from typing import Dict, List, NamedTuple, Tuple


class VisualPart(NamedTuple):
    category: str
    name: str
    level: int
    cost: int
    rep: float

    @property
    def item_name(self) -> str:
        return f"{self.category}: {self.name}"


VISUAL_PARTS: Tuple[VisualPart, ...] = (
'''
footer = '''
)

PART_CATEGORIES: Tuple[str, ...] = tuple(dict.fromkeys(p.category for p in VISUAL_PARTS))
PARTS_BY_ITEM: Dict[str, VisualPart] = {p.item_name: p for p in VISUAL_PARTS}


def parts_of(category: str, level: int) -> List[VisualPart]:
    return [p for p in VISUAL_PARTS if p.category == category and p.level == level]
'''
out_path.write_text(header + "\n".join(lines) + footer, encoding="utf-8")
from collections import Counter
print(len(unique), "parts", Counter((p[0], p[2]) for p in unique))
