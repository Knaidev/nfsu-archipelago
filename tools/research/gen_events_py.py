"""Generate worlds/nfsu/data/events.py from parsed events.json + reputation requirements."""
import json, re, sys, pathlib

research = pathlib.Path(sys.argv[1])
out_path = pathlib.Path(sys.argv[2])
events = json.loads((research / "events.json").read_text(encoding="utf-8"))
raw = {e["num"]: e["wikitext"] or "" for e in json.loads((research / "events_raw.json").read_text(encoding="utf-8"))}

BASE_TYPE = {"Tournament (Circuit)": ("Circuit", True), "Tournament (Drag)": ("Drag", True),
             "Tournament (Drift)": ("Drift", True), "Tournament (Sprint)": ("Sprint", True)}

lines = []
for e in events:
    n = e["num"]
    w = raw[n]
    rt, tourn = BASE_TYPE.get(e["type"], (e["type"], False))
    rep = re.search(r"font-weight: bold\">x(\d)</span>\{\{NFSUG1_InfoIcon\|rep\}\}", w)
    rep = int(rep.group(1)) if rep else None
    optional = "choose to decline" in w
    ib, rw = e["bank_infobox"], e["bank_rewards_section"]
    bank = tuple(rw[i] if rw[i] is not None else ib[i] for i in range(3))
    notes = []
    if e["bank_mismatch"] or None in ib:
        notes.append(f"bank differs on the wiki: infobox={ib} rewards={rw}")
    name = re.sub(r"<nowiki>(.*?)</nowiki>", r"\1", e["name"]).replace("‘", "'").replace("’", "'")
    unlocks = []
    for k, items in e["unlocks"].items():
        for it in items:
            unlocks.append(f"{k}: {it}")
    comment = f"  # {'; '.join(notes)}" if notes else ""
    lines.append(
        f"    EventData({n}, {name!r}, {rt!r}, {tourn}, {e['set']}, {bank!r}, {rep!r}, {optional},\n"
        f"              {tuple(unlocks)!r}),{comment}")

header = '''"""Underground Mode event data for Need for Speed: Underground (PS2).

Generated by tools/research/gen_events_py.py from the NFS Wiki (retrieved 2026-11-04):
  - Event list, sets, types: https://nfs.fandom.com/wiki/Need_for_Speed:_Underground/Underground_Mode
  - Per-event bank, reputation requirement, unlocks: the individual event pages
    (https://nfs.fandom.com/wiki/<Event_Name>), "Rewards" and "Unlocks" sections.

Event 0 is the prologue, event 112 the epilogue (vs. Melissa, after the credits).
The Archipelago world uses events 1-111; 0 and 112 are kept here for reference.

Fields:
  bank                 Bank reward (Easy, Medium, Hard) on first win. Taken from the
                       page's "Rewards" section; falls back to the infobox. Disagreements are noted.
  reputation_required  Minimum reputation multiplier ("x N", shown as stars) needed to enter.
                       None = no requirement listed on the wiki.
  optional             Event can be declined in vanilla (time trials, #110).
  vanilla_unlocks      What winning the event unlocks in the unmodified game.
"""
from typing import NamedTuple, Optional, Tuple


class EventData(NamedTuple):
    number: int
    name: str
    race_type: str          # Circuit, Sprint, Drag, Drift, Knockout, Time Trial
    tournament: bool
    set: int                # vanilla "set"; all events of a set must be won to open the next set
    bank: Tuple[Optional[int], Optional[int], Optional[int]]
    reputation_required: Optional[int]
    optional: bool
    vanilla_unlocks: Tuple[str, ...]


EVENTS: Tuple[EventData, ...] = (
'''
footer = '''
)

EVENTS_BY_NUMBER = {e.number: e for e in EVENTS}
GOAL_EVENT = 111
CAREER_EVENTS = tuple(e for e in EVENTS if 1 <= e.number <= 111)
TIME_TRIALS = tuple(e.number for e in CAREER_EVENTS if e.race_type == "Time Trial")
'''
out_path.parent.mkdir(parents=True, exist_ok=True)
out_path.write_text(header + "\n".join(lines) + footer, encoding="utf-8")
print("wrote", out_path, len(lines), "events")
